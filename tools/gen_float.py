#!/usr/bin/env python3
# Generates data/languages/v850_float.sinc: the V850E2V3 / RH850 (V850E3V5) floating-point
# instructions (format F:I, "reg2 111111 reg1 | reg3 subop").
#
#   python3 tools/gen_float.py        (from the repository root)
#
# Encodings are from the V850E2M and RH850G3KH software manuals and were checked instruction by
# instruction against GNU objdump. Field names follow v850_common.sinc: R1115 = reg2,
# R0004 = reg1 (or a sub-opcode for one-source instructions), R2731 = reg3, op1620/op2126 = the
# low 11 bits of the second halfword.
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "languages", "v850_float.sinc")

# operand kinds: S = 32-bit register, D = 64-bit register pair (even register, shown by its
# first register as in the manual and objdump)
# (name, sub-op in the reg1 field or None when reg1 is an operand, second-halfword bits 0-10,
#  source kinds, destination kind, semantic template, availability)
#   availability: "all" (V850E2V3 and RH850), "e2" (V850E2V3 only), "e3" (RH850 only)
T = []


def unop(name, sub, sec, src, dst, expr, avail="all"):
    T.append((name, sub, sec, (src,), dst, expr, avail))


def binop(name, sec, kind, expr, avail="all"):
    T.append((name, None, sec, (kind, kind), kind, expr, avail))


for k, sfx, d in (("D", "d", 0x10), ("S", "s", 0x00)):
    binop("addf." + sfx, 0x460 | d, k, "{2} f+ {1}")
    binop("subf." + sfx, 0x462 | d, k, "{2} f- {1}")
    binop("mulf." + sfx, 0x464 | d, k, "{2} f* {1}")
    binop("divf." + sfx, 0x46e | d, k, "{2} f/ {1}")
    binop("maxf." + sfx, 0x468 | d, k, "max")
    binop("minf." + sfx, 0x46a | d, k, "min")
    unop("absf." + sfx, 0x00, 0x448 | d, k, k, "abs({2})")
    unop("negf." + sfx, 0x01, 0x448 | d, k, k, "f- {2}")
    unop("sqrtf." + sfx, 0x00, 0x44e | d, k, k, "sqrt({2})")
    unop("recipf." + sfx, 0x01, 0x44e | d, k, k, "recip")
    unop("rsqrtf." + sfx, 0x02, 0x44e | d, k, k, "rsqrt")

# float -> integer with an explicit rounding: <op>f.<src><dst>
# src: s (single) / d (double); dst: w, uw (32-bit), l, ul (64-bit)
for op, base, fn in (("roundf", 0x00, "round"), ("trncf", 0x01, "trunc"),
                     ("ceilf", 0x02, "ceil"), ("floorf", 0x03, "floor")):
    for src, sk, sbit in (("s", "S", 0x000), ("d", "D", 0x010)):
        for dst, dk, dbit, uns in (("w", "S", 0x0, 0), ("uw", "S", 0x0, 1), ("l", "D", 0x4, 0), ("ul", "D", 0x4, 1)):
            unop("%s.%s%s" % (op, src, dst), base | (0x10 if uns else 0), 0x440 | sbit | dbit, sk, dk, "f2i:" + fn)

# conversions cvtf.<src><dst> (rounding by the current mode, modelled as round-to-nearest)
for name, sub, sec, sk, dk, expr in (
        ("cvtf.sw", 0x04, 0x440, "S", "S", "f2i:round"), ("cvtf.suw", 0x14, 0x440, "S", "S", "f2i:round"),
        ("cvtf.sl", 0x04, 0x444, "S", "D", "f2i:round"), ("cvtf.sul", 0x14, 0x444, "S", "D", "f2i:round"),
        ("cvtf.dw", 0x04, 0x450, "D", "S", "f2i:round"), ("cvtf.duw", 0x14, 0x450, "D", "S", "f2i:round"),
        ("cvtf.dl", 0x04, 0x454, "D", "D", "f2i:round"), ("cvtf.dul", 0x14, 0x454, "D", "D", "f2i:round"),
        ("cvtf.ws", 0x00, 0x442, "S", "S", "i2f"), ("cvtf.uws", 0x10, 0x442, "S", "S", "u2f"),
        ("cvtf.ls", 0x01, 0x442, "D", "S", "i2f"), ("cvtf.uls", 0x11, 0x442, "D", "S", "u2f"),
        ("cvtf.wd", 0x00, 0x452, "S", "D", "i2f"), ("cvtf.uwd", 0x10, 0x452, "S", "D", "u2f"),
        ("cvtf.ld", 0x01, 0x452, "D", "D", "i2f"), ("cvtf.uld", 0x11, 0x452, "D", "D", "u2f"),
        ("cvtf.sd", 0x02, 0x452, "S", "D", "f2f"), ("cvtf.ds", 0x03, 0x452, "D", "S", "f2f")):
    unop(name, sub, sec, sk, dk, expr)
# cvtf.hs / cvtf.sh and the RH850 fused multiply-add group (fmaf.s ...) are in v850e3.sinc

L = ["# Generated by tools/gen_float.py; do not edit.", ""]
L.append("# even registers shown by name, exporting the 64-bit pair")
for d, f, pf in (("D0004", "xR0004", "R0004pair"), ("D1115", "xR1115", "R1115pair"), ("D2731", "xR2731", "R2731pair")):
    L.append("%s: %s is %s & %s { export %s; }" % (d, f, f, pf, pf))
L.append("")
L.append("""macro fcc_get(res, bit) {
	res = (FPSR >> (24 + bit)) & 1;
}
macro fcc_set(bit, val) {
	local m:4 = 1 << (24 + bit);
	FPSR = (FPSR & ~m) | (zext(val != 0) << (24 + bit));
}
macro fcompare(res, cond, a, b) {
	local un:1 = nan(a) || nan(b);
	local r:1 = ((cond & 1) != 0 && un) || ((cond & 2) != 0 && !un && (a f== b)) ||
		((cond & 4) != 0 && !un && (a f< b));
	res = r;
}
""")
L.append('attach names [fcond2730]')
L.append('  ["f/t" "un/or" "eq/neq" "ueq/ogl" "olt/uge" "ult/oge" "ole/ugt" "ule/ogt"')
L.append('   "sf/st" "ngle/gle" "seq/sne" "ngl/gl" "lt/nlt" "nge/ge" "le/nle" "ngt/gt"];')
L.append("")

REG = {"S": ("R0004", "R1115", "R2731"), "D": ("D0004", "D1115", "D2731")}


def body(expr, srcs, dst, sk, dk):
    r1, r2, r3 = srcs  # reg1, reg2, reg3 names (reg1 may be None)
    if expr == "max":
        return "if (%s f< %s) goto <b>; %s = %s; goto <e>; <b> %s = %s; <e>" % (r2, r1, r3, r2, r3, r1)
    if expr == "min":
        return "if (%s f< %s) goto <b>; %s = %s; goto <e>; <b> %s = %s; <e>" % (r1, r2, r3, r2, r3, r1)
    if expr == "recip":
        return "local one:%d = int2float(1:4); %s = one f/ %s;" % (8 if dk == "D" else 4, r3, r2)
    if expr == "rsqrt":
        return "local one:%d = int2float(1:4); %s = one f/ sqrt(%s);" % (8 if dk == "D" else 4, r3, r2)
    if expr.startswith("f2i:"):
        fn = expr[4:]
        if fn == "trunc":
            return "%s = trunc(%s);" % (r3, r2)
        return "local t:%d = %s(%s); %s = trunc(t);" % (8 if sk == "D" else 4, fn, r2, r3)
    if expr == "i2f":
        return "%s = int2float(%s);" % (r3, r2)
    if expr == "u2f":
        # unsigned source: widen with a zero extension first
        w = 16 if sk == "D" else 8
        return "local u:%d = zext(%s); %s = int2float(u);" % (w, r2, r3)
    if expr == "f2f":
        return "%s = float2float(%s);" % (r3, r2)
    if expr == "h2s":
        return "%s = __float_half_to_single(%s);" % (r3, r2)
    if expr == "s2h":
        return "%s = __float_single_to_half(%s);" % (r3, r2)
    return "%s = %s;" % (r3, expr.replace("{2}", r2))


def emit(name, sub, sec, kinds, dk, expr, avail):
    if sub is None:  # reg1, reg2, reg3
        k = kinds[0]
        r1, r2, r3 = REG[k]
        disp = "%s %s, %s, %s" % (name, r1, r2, r3)
        nz = " & op0004!=0" if name == "divf.s" else ""
        pat = "%s & op0510=0x3F & %s%s; %s & op2126=0x%x & op1620=0x%x" % (r2, r1, nz, r3, sec >> 5, sec & 0x1f)
        b = "%s = %s;" % (r3, expr.replace("{1}", r1).replace("{2}", r2)) if expr not in ("max", "min") else body(expr, (r1, r2, r3), r3, k, k)
    else:  # reg2, reg3
        sk = kinds[0]
        r2 = REG[sk][1]
        r3 = REG[dk][2]
        disp = "%s %s, %s" % (name, r2, r3)
        pat = "%s & op0510=0x3F & op0004=0x%x; %s & op2126=0x%x & op1620=0x%x" % (r2, sub, r3, sec >> 5, sec & 0x1f)
        b = body(expr, (None, r2, r3), r3, sk, dk)
    return ":%s is %s {\n\t%s\n}" % (disp, pat, b)


for avail in ("all", "e2", "e3"):
    if avail == "e2":
        L.append("@ifdef V850E2M")
    elif avail == "e3":
        L.append("@ifdef V850E3")
    for e in T:
        if e[6] == avail:
            L.append(emit(*e))
    if avail != "all":
        L.append("@endif")
    L.append("")

L.append("""# CMOVF.S/D fcbit, reg1, reg2, reg3: reg3 = CC[fcbit] ? reg1 : reg2
:cmovf.s fcbit1719, R0004, R1115, xR2731 is R1115 & op0510=0x3F & R0004; xR2731 & op2731!=0 & op2126=0x20 & op2020=0 & fcbit1719 & op1616=0 {
	local c:4; fcc_get(c, fcbit1719);
	if (c != 0) goto <t>; xR2731 = R1115; goto <e>; <t> xR2731 = R0004; <e>
}
:cmovf.d fcbit1719, D0004, D1115, D2731 is D1115 & op0510=0x3F & D0004; D2731 & op2731!=0 & op2126=0x20 & op2020=1 & fcbit1719 & op1616=0 {
	local c:4; fcc_get(c, fcbit1719);
	if (c != 0) goto <t>; D2731 = D1115; goto <e>; <t> D2731 = D0004; <e>
}

# CMPF.S/D fcond, reg2, reg1, fcbit
:cmpf.s fcond2730, R1115, R0004, fcbit1719 is R1115 & op0510=0x3F & R0004; op3131=0 & fcond2730 & op2126=0x21 & op2020=0 & fcbit1719 & op1616=0 {
	local r:1; fcompare(r, fcond2730:1, R1115, R0004); fcc_set(fcbit1719, r);
}
:cmpf.d fcond2730, D1115, D0004, fcbit1719 is D1115 & op0510=0x3F & D0004; op3131=0 & fcond2730 & op2126=0x21 & op2020=1 & fcbit1719 & op1616=0 {
	local r:1; fcompare(r, fcond2730:1, D1115, D0004); fcc_set(fcbit1719, r);
}

# TRFSR fcbit: Z = CC[fcbit]
:trfsr fcbit1719 is op1115=0 & op0510=0x3F & op0004=0; op2731=0 & op2126=0x20 & op2020=0 & fcbit1719 & op1616=0 {
	local c:4; fcc_get(c, fcbit1719); $(PSW_Z) = c:1;
}

@ifdef V850E2M
# MADDF.S/MSUBF.S/NMADDF.S/NMSUBF.S reg1, reg2, reg3, reg4 (V850E2V3)
:maddf.s R0004, R1115, R2731, reg4 is R1115 & op0510=0x3F & R0004; R2731 & op2426=0b101 & op2122=0b00 & op1616=0 & reg4 {
	reg4 = (R1115 f* R0004) f+ R2731;
}
:msubf.s R0004, R1115, R2731, reg4 is R1115 & op0510=0x3F & R0004; R2731 & op2426=0b101 & op2122=0b01 & op1616=0 & reg4 {
	reg4 = (R1115 f* R0004) f- R2731;
}
:nmaddf.s R0004, R1115, R2731, reg4 is R1115 & op0510=0x3F & R0004; R2731 & op2426=0b101 & op2122=0b10 & op1616=0 & reg4 {
	reg4 = f- ((R1115 f* R0004) f+ R2731);
}
:nmsubf.s R0004, R1115, R2731, reg4 is R1115 & op0510=0x3F & R0004; R2731 & op2426=0b101 & op2122=0b11 & op1616=0 & reg4 {
	reg4 = f- ((R1115 f* R0004) f- R2731);
}
@endif

""")
with open(OUT, "w") as f:
    f.write("\n".join(L))
print("wrote", OUT, sum(1 for l in L if l.startswith(":")), "constructors")
